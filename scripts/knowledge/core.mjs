/**
 * The memory engine's deterministic core (layers L0, L2 and L4; see docs/knowledge/README.md).
 *
 * Every extractor is a pure function of one source file's path and text, so a graph is a fold over
 * its sources and the same tree always produces the same bytes: no clock, no randomness, no
 * environment, no network. Callers pass the root and, where a date matters, the date.
 *
 * What the graph keeps is structure, never a version, digest or timestamp, so a dependency bump
 * or a tool pin changes none of it. Each source's fragment is hashed, and the hashes are stored in
 * graph.json to name exactly which sources a stale graph disagrees with.
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync } from "node:fs";
import { join, posix } from "node:path";

export const SCHEMA_VERSION = 1;
export const KNOWLEDGE_DIR = "docs/knowledge";
export const EPISODES_DIR = `${KNOWLEDGE_DIR}/episodes`;
export const GRAPH_FILE = `${KNOWLEDGE_DIR}/graph.json`;
export const BRIEF_FILE = `${KNOWLEDGE_DIR}/README.md`;
export const EPISODES_INDEX = `${EPISODES_DIR}/README.md`;
export const SEMANTIC_FILE = `${KNOWLEDGE_DIR}/semantic.graph.json`;
export const MAX_GRAPH_BYTES = 1_000_000;
export const MAX_BRIEF_BYTES = 8_000;
export const EPISODE_KINDS = ["lesson", "incident", "decision"];

const SKIP_DIRS = new Set(["node_modules", ".git", "dist", "build", "coverage", "test-results", ".tools", ".venv", "graphify-out"]);
/** Generated by `sync`, so never a source of the graph it produces. */
const GENERATED = new Set([BRIEF_FILE, EPISODES_INDEX]);
/** Kinds whose node stands for a whole file, so a link to that path means a link to the node. */
const FILE_NODES = new Set(["doc", "adr", "skill", "agent", "prompt", "episode", "workflow", "module", "script"]);
export const compare = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
export const sha256 = (data) => createHash("sha256").update(data).digest("hex");

/** Files that exist and are tracked, or untracked and not ignored: what `git add -A` would commit. */
export function listFiles(root) {
  let names;
  try {
    names = execFileSync("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], {
      cwd: root,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
      stdio: ["ignore", "pipe", "ignore"],
    })
      .split("\0")
      .filter(Boolean);
  } catch {
    names = walk(root, "");
  }
  return [...new Set(names)]
    .filter((p) => !p.split("/").some((s) => SKIP_DIRS.has(s)))
    .filter((p) => existsSync(join(root, p)) && statSync(join(root, p)).isFile())
    .sort(compare);
}

/** Graph sources whose working-tree content differs from the index, or that are not staged at all: what a partial commit would leave out. */
export function unstagedSources(root) {
  const run = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 64 * 1024 * 1024 }).split("\0").filter(Boolean);
  const paths = new Set([...run("diff", "--name-only", "-z"), ...run("ls-files", "-z", "--others", "--exclude-standard")]);
  // A deletion that is not staged counts too: the commit would still hold the file the graph no longer lists.
  return [...paths].filter((p) => sourceKind(p) !== null).sort(compare);
}

function walk(root, rel) {
  const out = [];
  for (const entry of readdirSync(join(root, rel), { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const path = rel === "" ? entry.name : `${rel}/${entry.name}`;
    if (entry.isDirectory()) out.push(...walk(root, path));
    else if (entry.isFile()) out.push(path);
  }
  return out;
}

const lines = (text) => text.replace(/\r\n/g, "\n").split("\n");

/** The leading `--- … ---` block as `key: value` pairs, and the line the body starts on. */
export function parseFrontmatter(text) {
  const all = lines(text);
  if (all[0] !== "---") return { fields: null, bodyStart: 0 };
  const end = all.indexOf("---", 1);
  if (end === -1) return { fields: null, bodyStart: 0 };
  const fields = {};
  for (const line of all.slice(1, end)) {
    const match = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(line);
    if (match) fields[match[1]] = match[2].trim().replace(/^(["'])(.*)\1$/, "$2");
  }
  return { fields, bodyStart: end + 1 };
}

const firstHeading = (all, fallback) => {
  let fenced = false;
  for (const line of all) {
    if (line.startsWith("```")) fenced = !fenced;
    else if (!fenced && line.startsWith("# ")) return line.slice(2).trim();
  }
  return fallback;
};

/** Markdown links to files in the repository, with the line each is on. Code is not links. */
function markdownLinks(all, from) {
  const out = [];
  let fenced = false;
  all.forEach((raw, index) => {
    if (raw.trimStart().startsWith("```")) {
      fenced = !fenced;
      return;
    }
    if (fenced) return;
    const line = raw.replace(/`[^`]*`/g, "");
    for (const match of line.matchAll(/\]\(([^)\s]+)\)/g)) {
      const target = match[1].split("#")[0];
      if (target === "" || /^[a-z][a-z0-9+.-]*:/i.test(target) || target.startsWith("/")) continue;
      const resolved = posix.normalize(posix.join(posix.dirname(from), target));
      if (!resolved.startsWith("..")) out.push({ toPath: resolved, line: index + 1 });
    }
  });
  return out;
}

const node = (id, kind, label, path, layer, extra = {}) => ({ id, kind, label, path, layer, ...extra });
const link = (from, to, type, path, line) => ({ from, to, type, source: `${path}:${line}` });
const pathLink = (from, toPath, type, path, line) => ({ from, toPath, type, source: `${path}:${line}` });

const ADR_FILE = /^docs\/adr\/(\d{4})-[^/]+\.md$/;
const SKILL_FILE = /^\.claude\/skills\/([^/]+)\/SKILL\.md$/;
const AGENT_FILE = /^\.github\/agents\/([^/]+)\.agent\.md$/;
const PROMPT_FILE = /^\.github\/prompts\/([^/]+)\.prompt\.md$/;
const EPISODE_FILE = /^docs\/knowledge\/episodes\/([^/]+)\.md$/;

/** What kind of source this path is, or null when the graph does not read it. */
export function sourceKind(path) {
  if (GENERATED.has(path)) return null;
  if (path.endsWith("/module.json")) return "module";
  if (/^\.github\/workflows\/[^/]+\.ya?ml$/.test(path)) return "workflow";
  if (path === "scripts/tools/tools.json") return "tools";
  if (/^(scripts|test|template)\/.+\.mjs$/.test(path)) return "script";
  if (!path.endsWith(".md") || path === "CHANGELOG.md") return null;
  if (EPISODE_FILE.test(path)) return "episode";
  if (ADR_FILE.test(path)) return "adr";
  if (SKILL_FILE.test(path)) return "skill";
  if (AGENT_FILE.test(path)) return "agent";
  if (PROMPT_FILE.test(path)) return "prompt";
  return "doc";
}

function adrStatus(statusLine) {
  return statusLine.slice("**Status:**".length).split("·")[0].replace(/\[([^\]]*)\]\([^)]*\)/g, "$1").trim();
}

function extractEpisode(path, all, fields) {
  const name = EPISODE_FILE.exec(path)[1];
  const id = `episode:${name}`;
  const problems = [];
  const links = [];
  const e = fields ?? {};
  if (fields === null) problems.push(`${path}: an episode needs a frontmatter block (id, kind, title, validFrom, reviewBy, refs)`);
  if (e.id !== name) problems.push(`${path}: id must equal the file name \`${name}\`, found \`${e.id ?? ""}\``);
  if (!EPISODE_KINDS.includes(e.kind)) problems.push(`${path}: kind must be one of ${EPISODE_KINDS.join(", ")}`);
  if (!e.title) problems.push(`${path}: title is required`);
  for (const key of ["validFrom", "reviewBy"]) {
    if (!/^\d{4}-\d{2}-\d{2}$/.test(e[key] ?? "") || Number.isNaN(Date.parse(e[key]))) problems.push(`${path}: ${key} must be a YYYY-MM-DD date`);
  }
  if (e.validFrom && e.reviewBy && e.reviewBy < e.validFrom) problems.push(`${path}: reviewBy is before validFrom`);
  if (!/^\d{4}-\d{2}-\d{2}-/.test(name)) problems.push(`${path}: the file name must start with its YYYY-MM-DD date`);
  const refs = (e.refs ?? "").split(",").map((s) => s.trim()).filter(Boolean);
  const at = (key) => Math.max(1, all.findIndex((l) => l.startsWith(`${key}:`)) + 1);
  for (const ref of refs) links.push(link(id, ref, "about", path, at("refs")));
  if (e.supersedes) links.push(link(id, `episode:${e.supersedes}`, "supersedes", path, at("supersedes")));
  if (refs.length === 0 && !e.supersedes) problems.push(`${path}: refs must name at least one node the episode is about, for example adr:0001`);
  const n = node(id, "episode", e.title || name, path, "L4", { episodeKind: e.kind ?? "", validFrom: e.validFrom ?? "", reviewBy: e.reviewBy ?? "" });
  return { id, nodes: [n], links, problems };
}

function extractMarkdown(path, text, kind) {
  const all = lines(text);
  const { fields, bodyStart } = parseFrontmatter(text);
  const heading = firstHeading(all, path);
  let part;
  if (kind === "episode") {
    part = extractEpisode(path, all, fields);
  } else if (kind === "adr") {
    const id = `adr:${ADR_FILE.exec(path)[1]}`;
    const at = all.findIndex((l) => l.startsWith("**Status:**"));
    const links = [];
    if (at !== -1) {
      // A status reads "Accepted · Amends ADR-0018 · **Date:** ...": every clause before the date can name a relationship.
      for (const clause of all[at].split("**Date:**")[0].split("·")) {
        for (const match of clause.matchAll(/\b(supersedes|superseded by|amends|amended by)\b([^;]*)/gi)) {
          const verb = match[1].toLowerCase();
          for (const num of match[2].matchAll(/\b(\d{4})\b/g)) {
            const other = `adr:${num[1]}`;
            if (verb === "supersedes" || verb === "amends") links.push(link(id, other, verb, path, at + 1));
            else links.push(link(other, id, verb === "superseded by" ? "supersedes" : "amends", path, at + 1));
          }
        }
      }
    }
    part = { id, nodes: [node(id, "adr", heading.replace(/^ADR-\d{4}:\s*/, ""), path, "L2", { status: at === -1 ? "" : adrStatus(all[at]) })], links, problems: [] };
  } else if (kind === "skill" || kind === "agent" || kind === "prompt") {
    const pattern = kind === "skill" ? SKILL_FILE : kind === "agent" ? AGENT_FILE : PROMPT_FILE;
    const name = pattern.exec(path)[1];
    const id = `${kind}:${name}`;
    const extra = fields?.description ? { summary: fields.description.slice(0, 160) } : {};
    part = { id, nodes: [node(id, kind, fields?.name || name, path, "L1", extra)], links: [], problems: [] };
  } else {
    const id = `doc:${path}`;
    part = { id, nodes: [node(id, "doc", heading, path, "L2")], links: [], problems: [] };
  }
  const body = all.map((l, i) => (i < bodyStart ? "" : l));
  for (const found of markdownLinks(body, path)) part.links.push(pathLink(part.id, found.toPath, "links-to", path, found.line));
  return { nodes: part.nodes, links: part.links, problems: part.problems };
}

function parseJson(path, text) {
  try {
    return { data: JSON.parse(text) };
  } catch {
    return { problem: `${path}: not valid JSON` };
  }
}

function extractModule(path, text) {
  const { data, problem } = parseJson(path, text);
  if (problem) return { nodes: [], links: [], problems: [problem] };
  if (typeof data.id !== "string" || data.id === "") return { nodes: [], links: [], problems: [`${path}: module.json has no id`] };
  const dir = posix.dirname(path);
  const extra = { dir, ...(typeof data.toolchain === "string" ? { toolchain: data.toolchain } : {}) };
  return { nodes: [node(`module:${data.id}`, "module", data.id, path, "L2", extra)], links: [], problems: [], module: { id: `module:${data.id}`, dir } };
}

function extractTools(path, text) {
  const { data, problem } = parseJson(path, text);
  if (problem) return { nodes: [], links: [], problems: [problem] };
  const nodes = [];
  const links = [];
  for (const name of Object.keys(data.tools ?? {}).sort(compare)) {
    nodes.push(node(`tool:${name}`, "tool", name, path, "L2"));
    links.push(link(`tool:${name}`, `file:${path}`, "pinned-in", path, 1));
  }
  return { nodes, links, problems: [] };
}

function extractWorkflow(path, text) {
  const all = lines(text);
  const file = posix.basename(path);
  const wf = `workflow:${file}`;
  const jobId = (name) => `job:${file}/${name}`;
  const nodes = [node(wf, "workflow", file, path, "L2")];
  const links = [];
  let inJobs = false;
  let job = null;
  let needsBlock = false;
  all.forEach((line, index) => {
    const n = index + 1;
    if (/^jobs:\s*$/.test(line)) {
      inJobs = true;
      return;
    }
    if (!inJobs) return;
    if (/^\S/.test(line) && !line.startsWith("#")) {
      inJobs = false;
      return;
    }
    const jobMatch = /^ {2}([A-Za-z0-9_-]+):\s*(?:#.*)?$/.exec(line);
    if (jobMatch) {
      job = jobMatch[1];
      needsBlock = false;
      nodes.push(node(jobId(job), "job", job, path, "L2"));
      links.push(link(wf, jobId(job), "defines", path, n));
      return;
    }
    if (job === null) return;
    const needs = /^ {4}needs:\s*(.*)$/.exec(line);
    if (needs) {
      const rest = needs[1].replace(/#.*$/, "").trim();
      needsBlock = rest === "";
      for (const dep of rest.replace(/[[\]]/g, "").split(",").map((s) => s.trim()).filter(Boolean)) links.push(link(jobId(job), jobId(dep), "needs", path, n));
      return;
    }
    if (needsBlock) {
      const item = /^ {6}-\s*([A-Za-z0-9_-]+)\s*(?:#.*)?$/.exec(line);
      if (item) links.push(link(jobId(job), jobId(item[1]), "needs", path, n));
      else if (!/^\s*(#.*)?$/.test(line)) needsBlock = false;
    }
    const uses = /^ {4}uses:\s*\.\/(\.github\/workflows\/[^\s#]+)/.exec(line);
    if (uses) links.push(pathLink(jobId(job), uses[1], "calls", path, n));
  });
  return { nodes, links, problems: [] };
}

function extractScript(path, text) {
  const id = `script:${path}`;
  const links = [];
  // Whole-text matching, because a formatter wraps a long import over several lines. The clause between
  // the keyword and `from` holds only identifier characters, so a quoted string in code never matches.
  const declarations = [...text.matchAll(/^[ \t]*(?:import|export)\b[\w\s{},*$]*?\bfrom\s+["'](\.{1,2}\/[^"']+)["']/gm), ...text.matchAll(/^[ \t]*import\s+["'](\.{1,2}\/[^"']+)["']/gm)];
  for (const match of declarations) {
    const line = text.slice(0, match.index).split("\n").length;
    links.push(pathLink(id, posix.normalize(posix.join(posix.dirname(path), match[1])), "imports", path, line));
  }
  return { nodes: [node(id, "script", path, path, "L2")], links, problems: [] };
}

/** One source's contribution to the graph. Pure: the same path and text always give the same fragment. */
export function extractFragment(path, text) {
  const kind = sourceKind(path);
  if (kind === null) return null;
  if (kind === "module") return extractModule(path, text);
  if (kind === "tools") return extractTools(path, text);
  if (kind === "workflow") return extractWorkflow(path, text);
  if (kind === "script") return extractScript(path, text);
  return extractMarkdown(path, text, kind);
}

/** Fold every source's fragment into a sorted, deduplicated graph. Reads files, writes nothing. */
export function buildGraph(root, files = listFiles(root)) {
  const fragments = [];
  const sources = {};
  const problems = [];
  // The files `sync` itself writes count as present, so rebuilding after one is deleted gives the same graph.
  const present = new Set([...files, ...GENERATED]);
  for (const path of files) {
    if (sourceKind(path) === null) continue;
    const fragment = extractFragment(path, readFileSync(join(root, path), "utf8"));
    sources[path] = sha256(JSON.stringify({ nodes: fragment.nodes, links: fragment.links }));
    problems.push(...fragment.problems);
    fragments.push({ path, ...fragment });
  }
  const nodes = new Map();
  for (const f of fragments) {
    for (const n of f.nodes) {
      if (nodes.has(n.id)) problems.push(`${f.path}: \`${n.id}\` is already defined by ${nodes.get(n.id).path}`);
      else nodes.set(n.id, n);
    }
  }
  const byPath = new Map([...nodes.values()].filter((n) => FILE_NODES.has(n.kind)).map((n) => [n.path, n.id]));
  const edges = new Map();
  const add = (e) => {
    const key = `${e.from}\0${e.to}\0${e.type}`;
    const prior = edges.get(key);
    if (!prior || compare(e.source, prior.source) < 0) edges.set(key, e);
  };
  const superseded = new Set(fragments.flatMap((f) => f.links).filter((l) => l.type === "supersedes").map((l) => l.to));
  const ensureFile = (path) => {
    if (!present.has(path)) return null;
    const id = `file:${path}`;
    if (!nodes.has(id)) nodes.set(id, node(id, "file", path, path, "L2"));
    return id;
  };
  for (const f of fragments) {
    for (const l of f.links) {
      let to = l.to;
      if (l.toPath !== undefined) to = byPath.get(l.toPath) ?? ensureFile(l.toPath);
      else if (to.startsWith("file:")) to = ensureFile(to.slice(5)) ?? to;
      if (!to) continue;
      if (!nodes.has(to)) {
        // A superseded episode is immutable, so it keeps pointing at what has since moved; an active one may not.
        // A supersession target is never exempt: episodes cannot be deleted, so it cannot have gone.
        if (nodes.get(l.from)?.layer === "L4" && !(l.type === "about" && superseded.has(l.from))) problems.push(`${l.source}: \`${to}\` is not a node, so this episode points at nothing. Update its refs, or supersede it`);
        continue;
      }
      add({ from: l.from, to, type: l.type, source: l.source });
    }
    // The root module (dir ".") would own every document, so only a nested module owns the pages beside it.
    if (f.module && f.module.dir !== ".") {
      for (const [path, id] of byPath) {
        if (id.startsWith("doc:") && path.startsWith(`${f.module.dir}/`)) add({ from: f.module.id, to: id, type: "documents", source: `${f.path}:1` });
      }
    }
  }
  const sortedNodes = [...nodes.values()].sort((a, b) => compare(a.id, b.id));
  const sortedEdges = [...edges.values()].sort((a, b) => compare(a.from, b.from) || compare(a.to, b.to) || compare(a.type, b.type));
  const sortedSources = Object.fromEntries(Object.entries(sources).sort(([a], [b]) => compare(a, b)));
  problems.push(...supersessionProblems(sortedEdges));
  return { graph: { schemaVersion: SCHEMA_VERSION, sources: sortedSources, nodes: sortedNodes, edges: sortedEdges }, problems: [...new Set(problems)].sort(compare) };
}

/** A superseded episode must be an episode, and supersession must not loop. */
function supersessionProblems(edges) {
  const problems = [];
  const next = new Map();
  for (const e of edges) {
    if (e.type !== "supersedes" || !e.from.startsWith("episode:")) continue;
    if (e.to.startsWith("episode:")) next.set(e.from, e.to);
    else problems.push(`${e.source}: an episode can only supersede another episode`);
  }
  for (const start of next.keys()) {
    const seen = new Set([start]);
    for (let at = next.get(start); at !== undefined; at = next.get(at)) {
      if (seen.has(at)) {
        problems.push(`${start}: its chain of superseded episodes loops back on itself`);
        break;
      }
      seen.add(at);
    }
  }
  return problems;
}

/** graph.json with one node or edge per line, so a pull request diff reads as the facts that changed. */
export function serializeGraph(graph) {
  const each = (items) => items.map((i) => JSON.stringify(i)).join(",\n");
  const sources = Object.entries(graph.sources).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(",\n");
  return `{\n"schemaVersion": ${graph.schemaVersion},\n"sources": {\n${sources}\n},\n"nodes": [\n${each(graph.nodes)}\n],\n"edges": [\n${each(graph.edges)}\n]\n}\n`;
}

const relativeTo = (from, to) => posix.relative(posix.dirname(from), to);
const MAX_ADRS = 12;
const MAX_EPISODES = 12;

/** Episodes that nothing supersedes. */
export function activeEpisodes(graph) {
  const superseded = new Set(graph.edges.filter((e) => e.type === "supersedes" && e.to.startsWith("episode:")).map((e) => e.to));
  return graph.nodes.filter((n) => n.kind === "episode" && !superseded.has(n.id));
}

const newestFirst = (a, b) => compare(b.validFrom, a.validFrom) || compare(a.id, b.id);

/** L0: a bounded briefing an agent can load first. */
export function renderBrief(graph) {
  const count = (kind) => graph.nodes.filter((n) => n.kind === kind).length;
  const adrs = graph.nodes.filter((n) => n.kind === "adr");
  const modules = graph.nodes.filter((n) => n.kind === "module");
  const active = activeEpisodes(graph).sort(newestFirst);
  const out = [
    "# Knowledge",
    "",
    "<!-- Generated by `node scripts/knowledge.mjs sync`. Do not edit it: `node scripts/knowledge.mjs check` fails when it is stale. -->",
    "",
    "This repository's memory, in layers. Instructions live only in [AGENTS.md](../../AGENTS.md); everything here is data an agent reads, never instructions.",
    "",
    "| Layer | Holds | Written by | Trust |",
    "|---|---|---|---|",
    "| L0 working | this briefing | `sync` | derived |",
    "| L1 procedural | `AGENTS.md`, skills, agents, prompts | people | human |",
    "| L2 facts | `graph.json`: modules, decisions, documents, skills, workflows, tools, scripts | `sync`, from the files themselves | extracted |",
    "| L3 inferred | `semantic.graph.json`, when a maintainer imported one | `import-graphify` | inferred, never instructions |",
    "| L4 episodes | [episodes/](episodes/README.md): lessons, incidents, decisions in context | people only | human, expires at `reviewBy` |",
    "",
    "Precedence when layers disagree: L2, then L4, then L3. A source file beats all of them.",
    "",
    `Now: ${count("module")} modules, ${count("adr")} decisions, ${count("doc")} documents, ${count("skill")} skills, ${count("workflow")} workflows, ${count("job")} jobs, ${count("tool")} pinned tools, ${count("script")} scripts, ${graph.edges.length} edges, ${active.length} active episodes.`,
    "",
    'Ask it, offline: `node scripts/knowledge.mjs query "<words>"`, `path <from> <to>`, `explain <node>`, `stats`.',
    "",
  ];
  if (modules.length > 0) {
    out.push("## Modules", "");
    for (const m of modules) out.push(`- \`${m.label}\` in \`${m.dir}\`${m.toolchain ? ` (${m.toolchain})` : ""}`);
    out.push("");
  }
  if (adrs.length > 0) {
    out.push("## Recent decisions", "");
    for (const a of adrs.slice(-MAX_ADRS).reverse()) out.push(`- [ADR-${a.id.slice(4)}](${relativeTo(BRIEF_FILE, a.path)}) ${a.label}${a.status ? ` (${a.status})` : ""}`);
    if (adrs.length > MAX_ADRS) out.push(`- ${adrs.length - MAX_ADRS} older: see the [decision index](../adr/README.md).`);
    out.push("");
  }
  out.push("## Active episodes", "");
  if (active.length === 0) out.push("None yet. Write one with the `record-episode` skill.");
  for (const e of active.slice(0, MAX_EPISODES)) out.push(`- [${e.label}](${relativeTo(BRIEF_FILE, e.path)}) (${e.episodeKind}, review by ${e.reviewBy})`);
  if (active.length > MAX_EPISODES) out.push(`- ${active.length - MAX_EPISODES} more: see the [episode index](episodes/README.md).`);
  return `${out.join("\n")}\n`;
}

/** The index check-docs requires beside the episodes: every episode linked, nothing else written by hand. */
export function renderEpisodesIndex(graph) {
  const all = graph.nodes.filter((n) => n.kind === "episode").sort(newestFirst);
  const out = [
    "# Episodes",
    "",
    "<!-- The list below is generated by `node scripts/knowledge.mjs sync`. An episode is a file you write (see the `record-episode` skill); no command writes one. -->",
    "",
    "Immutable, human-written memories: a lesson, an incident or a decision in its context. One file each, named by date. To change one, write a new episode that `supersedes` it.",
    "",
  ];
  if (all.length === 0) out.push("None yet.");
  for (const e of all) out.push(`- [${e.label}](${posix.basename(e.path)}) (${e.episodeKind}, from ${e.validFrom}, review by ${e.reviewBy})`);
  return `${out.join("\n")}\n`;
}

/** What `sync` writes, as path → bytes. */
export function expectedOutputs(graph) {
  return { [GRAPH_FILE]: serializeGraph(graph), [BRIEF_FILE]: renderBrief(graph), [EPISODES_INDEX]: renderEpisodesIndex(graph) };
}

/** Integrity rules for a graph read back from disk: every edge has provenance and both its ends. */
export function graphIntegrity(graph) {
  if (graph?.schemaVersion !== SCHEMA_VERSION) return [`${GRAPH_FILE}: schemaVersion is ${graph?.schemaVersion}, this engine writes ${SCHEMA_VERSION}`];
  const problems = [];
  const ids = new Set(graph.nodes.map((n) => n.id));
  for (const e of graph.edges) {
    if (!/^[^\s:][^\s]*:\d+$/.test(e.source ?? "")) problems.push(`edge ${e.from} -${e.type}-> ${e.to} has no file:line provenance`);
    if (!ids.has(e.from) || !ids.has(e.to)) problems.push(`edge ${e.from} -${e.type}-> ${e.to} points at a node that does not exist`);
  }
  return problems;
}

/** The sources a graph on disk disagrees with, by name. */
export function sourceDrift(onDisk, built) {
  const before = onDisk?.sources ?? {};
  const after = built.sources;
  return {
    added: Object.keys(after).filter((p) => !(p in before)),
    removed: Object.keys(before).filter((p) => !(p in after)),
    changed: Object.keys(after).filter((p) => p in before && before[p] !== after[p]),
  };
}
